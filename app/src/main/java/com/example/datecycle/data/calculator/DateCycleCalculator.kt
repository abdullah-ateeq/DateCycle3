package com.example.datecycle.data.calculator

import com.example.datecycle.data.model.DateCycleItem
import com.example.datecycle.data.model.DateCycleResult
import com.example.datecycle.data.model.IntervalUnit
import com.example.datecycle.data.model.MonthlyAnchorMode
import java.time.DateTimeException
import java.time.LocalDate
import java.time.temporal.ChronoUnit

object DateCycleCalculator {

    const val MIN_OCCURRENCES = 1
    const val MAX_OCCURRENCES = 500
    const val MIN_INTERVAL = 1
    const val MAX_INTERVAL = 9999

    sealed class ValidationResult {
        object Valid : ValidationResult()
        data class Error(val message: String) : ValidationResult()
    }

    fun validate(
        startDate: LocalDate?,
        intervalValue: Int?,
        intervalUnit: IntervalUnit?,
        occurrences: Int?,
        endDate: LocalDate?
    ): ValidationResult {
        if (startDate == null) {
            return ValidationResult.Error("Starting date is required.")
        }
        if (intervalValue == null || intervalValue < MIN_INTERVAL) {
            return ValidationResult.Error("Repeat interval must be at least $MIN_INTERVAL.")
        }
        if (intervalValue > MAX_INTERVAL) {
            return ValidationResult.Error("Repeat interval cannot exceed $MAX_INTERVAL.")
        }
        if (intervalUnit == null) {
            return ValidationResult.Error("Please choose an interval unit.")
        }
        if (occurrences == null || occurrences < MIN_OCCURRENCES) {
            return ValidationResult.Error("Number of occurrences must be at least $MIN_OCCURRENCES.")
        }
        if (occurrences > MAX_OCCURRENCES) {
            return ValidationResult.Error("Number of occurrences cannot exceed $MAX_OCCURRENCES.")
        }
        if (endDate != null && endDate.isBefore(startDate)) {
            return ValidationResult.Error("End date cannot be earlier than starting date.")
        }
        return ValidationResult.Valid
    }

    /**
     * Calculates the repeating date series starting from [startDate].
     *
     * The first date generated is [startDate] (occurrence #1).
     * Subsequent dates are generated by stepping [intervalValue] [intervalUnit] each time.
     * Stops when [occurrences] count is reached or when a date surpasses [endDate].
     */
    fun calculate(
        startDate: LocalDate,
        intervalValue: Int,
        intervalUnit: IntervalUnit,
        occurrences: Int,
        endDate: LocalDate? = null,
        monthlyAnchorMode: MonthlyAnchorMode = MonthlyAnchorMode.PRESERVE_ORIGINAL_DAY
    ): DateCycleResult {
        val clampedOccurrences = occurrences.coerceIn(MIN_OCCURRENCES, MAX_OCCURRENCES)
        val validInterval = intervalValue.coerceAtLeast(MIN_INTERVAL)

        val resultList = mutableListOf<DateCycleItem>()
        var stoppedByEnd = false
        var cascadeDate = startDate

        for (step in 0 until clampedOccurrences) {
            val date: LocalDate = try {
                when (intervalUnit) {
                    IntervalUnit.DAYS -> {
                        startDate.plusDays(step.toLong() * validInterval)
                    }
                    IntervalUnit.WEEKS -> {
                        startDate.plusWeeks(step.toLong() * validInterval)
                    }
                    IntervalUnit.MONTHS -> {
                        when (monthlyAnchorMode) {
                            MonthlyAnchorMode.PRESERVE_ORIGINAL_DAY -> {
                                // Anchor to original day of month:
                                // Java's LocalDate.plusMonths naturally handles clamping shorter months
                                // (e.g., Jan 31 + 1 month = Feb 28/29, Jan 31 + 2 months = Mar 31)
                                startDate.plusMonths(step.toLong() * validInterval)
                            }
                            MonthlyAnchorMode.CLAMP_AND_CASCADE -> {
                                if (step == 0) {
                                    cascadeDate = startDate
                                    cascadeDate
                                } else {
                                    cascadeDate = cascadeDate.plusMonths(validInterval.toLong())
                                    cascadeDate
                                }
                            }
                        }
                    }
                    IntervalUnit.YEARS -> {
                        // For leap years: 2024-02-29 + 1 year = 2025-02-28, + 4 years = 2028-02-29
                        startDate.plusYears(step.toLong() * validInterval)
                    }
                }
            } catch (e: DateTimeException) {
                // If date exceeds year 999999999 or calendar limit, safely stop
                break
            }

            if (endDate != null && date.isAfter(endDate)) {
                stoppedByEnd = true
                break
            }

            val daysFromStart = ChronoUnit.DAYS.between(startDate, date)
            val previousDate = if (resultList.isEmpty()) startDate else resultList.last().date
            val daysFromPrevious = ChronoUnit.DAYS.between(previousDate, date)

            resultList.add(
                DateCycleItem(
                    index = step + 1,
                    date = date,
                    daysFromStart = daysFromStart,
                    daysFromPrevious = daysFromPrevious
                )
            )
        }

        return DateCycleResult(
            startDate = startDate,
            intervalValue = validInterval,
            intervalUnit = intervalUnit,
            requestedOccurrences = clampedOccurrences,
            endDate = endDate,
            monthlyAnchorMode = monthlyAnchorMode,
            dates = resultList,
            stoppedByEndDate = stoppedByEnd
        )
    }
}
